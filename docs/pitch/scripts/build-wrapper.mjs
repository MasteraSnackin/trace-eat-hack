import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// The composition island is the only editable source of slide order and notes.
// The official standalone player needs that island in its wrapper as well.
const projectDir = fileURLToPath(new URL('../', import.meta.url));
const composition = await readFile(`${projectDir}composition/index.html`, 'utf8');
const islands = [...composition.matchAll(/<script\b[^>]*type=["']application\/hyperframes-slideshow\+json["'][^>]*>([\s\S]*?)<\/script>/gi)];
if (islands.length !== 1) throw new Error('Expected exactly one slideshow JSON island.');
const manifest = JSON.parse(islands[0][1]);
const scenes = new Map();
for (const match of composition.matchAll(/<[a-z][a-z0-9-]*\b[^>]*\bdata-composition-id=["'][^"']+["'][^>]*>/gi)) {
  const attrs = Object.fromEntries([...match[0].matchAll(/([\w-]+)=["']([^"']*)["']/g)].map((attribute) => [attribute[1], attribute[2]]));
  const id = attrs['data-composition-id'];
  const start = Number(attrs['data-start']);
  const duration = Number(attrs['data-duration']);
  if (scenes.has(id)) throw new Error(`Duplicate scene: ${id}`);
  if (!Number.isFinite(start) || !Number.isFinite(duration) || duration <= 0) throw new Error(`Invalid timing: ${id}`);
  scenes.set(id, { start, end: start + duration });
}

function withTiming(slide) {
  const scene = scenes.get(slide.sceneId);
  if (!scene) throw new Error(`No scene for slide: ${slide.sceneId}`);
  const timed = { ...slide, startTime: slide.startTime ?? scene.start, endTime: slide.endTime ?? scene.end };
  if (timed.endTime <= timed.startTime) throw new Error(`Invalid slide range: ${slide.sceneId}`);
  if ((timed.fragments ?? []).some((time) => !Number.isFinite(time) || time < timed.startTime || time > timed.endTime)) throw new Error(`Invalid fragment: ${slide.sceneId}`);
  return timed;
}
const wrapperManifest = {
  ...manifest,
  slides: manifest.slides.map(withTiming),
  slideSequences: (manifest.slideSequences ?? []).map((sequence) => ({ ...sequence, slides: sequence.slides.map(withTiming) })),
};
// Escaping '<' preserves the parsed notes exactly and prevents script termination.
const json = JSON.stringify(wrapperManifest, null, 2).replaceAll('<', '\\u003c');
const html = `<!doctype html>
<!-- Generated by scripts/build-wrapper.mjs; edit composition/index.html. -->
<html lang="en-GB">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="description" content="Trace: an animated EAT_HACK pitch about studying shelf browsing before checkout.">
    <title>Trace: EAT_HACK pitch</title>
    <script defer src="player/hyperframes-player.global.js"></script>
    <script defer src="player/hyperframes-slideshow.global.js"></script>
    <script>
      if (new URLSearchParams(location.search).get('mode') === 'audience') {
        document.title = 'Trace: audience display';
      }
    </script>
    <style>
      *, *::before, *::after { box-sizing: border-box; }
      html, body { width: 100%; height: 100%; margin: 0; overflow: hidden; background: #111d1a; }
      hyperframes-slideshow { display: block; position: relative; width: 100vw; height: 100vh; }
      hyperframes-player { position: absolute; inset: 0; }
      noscript { display: block; padding: 2rem; color: #fff; font: 1rem/1.5 system-ui, sans-serif; }
      noscript a { color: inherit; }
    </style>
  </head>
  <body>
    <hyperframes-slideshow tabindex="0" notes-storage-key="trace-eat-hack-pitch-v1" aria-label="Trace EAT_HACK pitch presentation">
      <hyperframes-player interactive src="composition/index.html"></hyperframes-player>
      <script type="application/hyperframes-slideshow+json">
${json}
      </script>
    </hyperframes-slideshow>
    <noscript>This animated presentation needs JavaScript. <a href="https://github.com/MasteraSnackin/trace-eat-hack/raw/refs/heads/main/docs/slides/Trace-EAT-HACK-judges-pitch.pptx">Download the editable PowerPoint</a>.</noscript>
  </body>
</html>
`;
await writeFile(`${projectDir}index.html`, html);
console.log(`Built wrapper for ${wrapperManifest.slides.length} slides with matching notes and explicit time bounds.`);
